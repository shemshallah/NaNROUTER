@dataclass(frozen=True)
class SyntheticTrialResult:
    """One condition/SNR/seed/repeat synthetic retrieval trial."""

    condition: str
    snr_db: float
    item_count: int
    seed: int
    repeat: int
    correct: int
    total: int
    false_matches: int
    null_total: int
    steps: int
    memory_bytes: int
    effective_noise_sigma: float
    noise_model: str

    @property
    def accuracy(self) -> float:
        return self.correct / self.total if self.total else 0.0

