class CapacitySNRError(ValueError):
    """Base class for capacity/SNR contract and generator failures."""


def _canonical_json(value: Any) -> str:
    return json.dumps(
        value, sort_keys=True, separators=(",", ":"), ensure_ascii=False
    )


def _sha256_text(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def _sha256_json(value: Any) -> str:
    return _sha256_text(_canonical_json(value))


def _seed_from(*parts: Any) -> int:
    return int(_sha256_text(":".join(map(str, parts)))[:16], 16)


def _mean(values: list[float]) -> float:
    if not values:
        return 0.0
    return sum(values) / len(values)


def _percentile(sorted_values: list[float], q: float) -> float:
    if not sorted_values:
        raise ValueError("percentile requires at least one value")
    if q <= 0.0:
        return sorted_values[0]
    if q >= 1.0:
        return sorted_values[-1]
    position = (len(sorted_values) - 1) * q
    lower = int(math.floor(position))
    upper = int(math.ceil(position))
    if lower == upper:
        return sorted_values[lower]
    fraction = position - lower
    return (
        sorted_values[lower]
        + (sorted_values[upper] - sorted_values[lower]) * fraction
    )


def _paired_bootstrap_ci(
    values: list[float],
    *,
    samples: int,
    confidence: float,
    seed: int,
) -> tuple[float | None, float | None]:
    if len(values) < 2:
        return None, None
    rng = random.Random(seed)
    n = len(values)
    means: list[float] = []
    for _ in range(samples):
        total = 0.0
        for _ in range(n):
            total += values[rng.randrange(n)]
        means.append(total / n)
    means.sort()
    alpha = (1.0 - confidence) / 2.0
    return (
        round(_percentile(means, alpha), 12),
        round(_percentile(means, 1.0 - alpha), 12),
    )


def _require_text(
    value: Any,
    name: str,
    *,
    maximum: int = 256,
    error_cls: type[CapacitySNRError] = CapacitySNRError,
) -> str:
    if (
        not isinstance(value, str)
        or not value.strip()
        or len(value) > maximum
    ):
        raise error_cls(
            f"{name} must be a non-empty string of at most {maximum} characters"
        )
    return value


def _require_int(
    value: Any,
    name: str,
    *,
    minimum: int = 0,
    error_cls: type[CapacitySNRError] = CapacitySNRError,
) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or value < minimum:
        raise error_cls(f"{name} must be an integer >= {minimum}")
    return value


def _require_number(
    value: Any,
    name: str,
    *,
    minimum: float | None = None,
    maximum: float | None = None,
    error_cls: type[CapacitySNRError] = CapacitySNRError,
) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise error_cls(f"{name} must be a finite number")
    number = float(value)
    if not math.isfinite(number):
        raise error_cls(f"{name} must be a finite number")
    if minimum is not None and number < minimum:
        raise error_cls(f"{name} must be >= {minimum}")
    if maximum is not None and number > maximum:
        raise error_cls(f"{name} must be <= {maximum}")
    return number


def _require_tuple(value: Any, name: str) -> tuple[Any, ...]:
    if isinstance(value, (str, bytes, bytearray)) or not isinstance(
        value, (tuple, list)
    ):
        raise CapacitySNRError(f"{name} must be a tuple or list")
    return tuple(value)


@dataclass(frozen=True)
class SNRPoint:
    """One declared SNR point with its explicit power definition."""

    snr_db: float
    definition: str = SNR_DEFINITION

    def __post_init__(self) -> None:
        object.__setattr__(
            self, "snr_db", _require_number(self.snr_db, "snr_db")
        )
        _require_text(self.definition, "SNR definition")

    def noise_power(self, signal_power: float = 1.0) -> float:
        signal = _require_number(
            signal_power, "signal_power", minimum=1e-300
        )
        return signal / (10.0 ** (self.snr_db / 10.0))

    def noise_sigma(self, signal_power: float = 1.0) -> float:
        return math.sqrt(self.noise_power(signal_power))

    def to_dict(self, signal_power: float = 1.0) -> dict[str, Any]:
        noise_power = self.noise_power(signal_power)
        return {
            "snr_db": self.snr_db,
            "definition": self.definition,
            "signal_power": signal_power,
            "noise_power": round(noise_power, 15),
            "noise_sigma": round(math.sqrt(noise_power), 15),
        }


def _default_snr_points() -> tuple[SNRPoint, ...]:
    return (SNRPoint(-12.0), SNRPoint(-8.0), SNRPoint(-4.0))


@dataclass(frozen=True)
class SNRSweep:
    """Declared SNR sweep, noise model, and measured/declared range."""

    points: tuple[SNRPoint, ...] = field(default_factory=_default_snr_points)
    signal_power: float = 1.0
    declared_range_db: tuple[float, float] | None = None
    noise_model: str = NOISE_MODEL_ID
    matched_variance_noise_model: str = MATCHED_VARIANCE_NOISE_MODEL_ID

    def __post_init__(self) -> None:
        points = _require_tuple(self.points, "sweep points")
        if not points:
            raise CapacitySNRError("sweep points cannot be empty")
        if any(not isinstance(point, SNRPoint) for point in points):
            raise CapacitySNRError("sweep points must be SNRPoint instances")
        ordered = tuple(sorted(points, key=lambda point: point.snr_db))
        if len({point.snr_db for point in ordered}) != len(ordered):
            raise CapacitySNRError("sweep points must have unique snr_db values")
        object.__setattr__(self, "points", ordered)
        object.__setattr__(
            self,
            "signal_power",
            _require_number(
                self.signal_power, "signal_power", minimum=1e-300
            ),
        )
        _require_text(self.noise_model, "noise_model")
        _require_text(
            self.matched_variance_noise_model,
            "matched_variance_noise_model",
        )
        if self.declared_range_db is None:
            declared = (ordered[0].snr_db, ordered[-1].snr_db)
        else:
            declared = _require_tuple(
                self.declared_range_db, "declared_range_db"
            )
            if len(declared) != 2:
                raise CapacitySNRError(
                    "declared_range_db must contain exactly two values"
                )
            low = _require_number(declared[0], "declared_range_db low")
            high = _require_number(declared[1], "declared_range_db high")
            if low > high:
                raise CapacitySNRError(
                    "declared_range_db low must be <= high"
                )
            declared = (low, high)
        object.__setattr__(self, "declared_range_db", declared)

    def noise_power(self, snr_db: float) -> float:
        return SNRPoint(snr_db).noise_power(self.signal_power)

    def noise_sigma(self, snr_db: float) -> float:
        return math.sqrt(self.noise_power(snr_db))

    def contains(self, snr_db: float) -> bool:
        low, high = self.declared_range_db  # type: ignore[misc]
        return low <= snr_db <= high

    def to_dict(self) -> dict[str, Any]:
        return {
            "points": [
                point.to_dict(self.signal_power) for point in self.points
            ],
            "snr_db_values": [point.snr_db for point in self.points],
            "signal_power": self.signal_power,
            "declared_range_db": list(self.declared_range_db or ()),
            "measured_range_db": [
                self.points[0].snr_db,
                self.points[-1].snr_db,
            ],
            "noise_model": self.noise_model,
            "matched_variance_noise_model": self.matched_variance_noise_model,
            "definition": SNR_DEFINITION,
        }


@dataclass(frozen=True)
class SeedSet:
    """Declared seed manifest; support requires at least ``min_seeds``."""

    seeds: tuple[int, ...] = (0, 1)
    min_seeds: int = 2

    def __post_init__(self) -> None:
        seeds = _require_tuple(self.seeds, "seeds")
        if not seeds:
            raise CapacitySNRError("seeds cannot be empty")
        for seed in seeds:
            _require_int(seed, "seed")
        if len(set(seeds)) != len(seeds):
            raise CapacitySNRError("seeds must be unique")
        object.__setattr__(self, "seeds", seeds)
        minimum = _require_int(self.min_seeds, "min_seeds", minimum=2)
        object.__setattr__(self, "min_seeds", minimum)

    def to_dict(self) -> dict[str, Any]:
        return {
            "seeds": list(self.seeds),
            "seed_count": len(self.seeds),
            "min_seeds": self.min_seeds,
        }


