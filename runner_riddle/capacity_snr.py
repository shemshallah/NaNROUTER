"""Synthetic capacity-versus-SNR harness for the R5 experiment plan.

This module is a deterministic *synthetic* control plane.  It does not load,
train, or call a real model.  It does not read a real dataset.  It cannot
produce a real capacity measurement and it deliberately marks every report as
non-promotable.

The synthetic frozen-model stub builds a deterministic Rademacher codebook,
adds Gaussian noise whose variance is derived from an explicit SNR definition,
and performs top-1 associative retrieval.  Experimental conditions transform
only the synthetic memory/noise path:

* matched baseline: local-only memory, no aperture coupling;
* coupled candidate: the same memory with a declared synthetic coupling gain;
* zero coupling: the candidate path with zero gain;
* random coupling: zero-gain candidate path with random sign scrambling;
* shuffled memory: candidate denoising with shifted memory associations;
* matched-variance noise: local baseline with AR(1)-colored noise whose
  stationary component variance equals the Gaussian noise variance.

The six R5 gates are evaluated over held-out synthetic retrievals.  A
``supported`` gate status means only that the synthetic generator met all six
conditions.  It is not evidence about a real model, real data, or real
capacity; ``promotable_as_real_capacity_result`` is always ``False``.
"""
